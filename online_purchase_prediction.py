# STEP 18: CSV UPLOAD PREDICTION FUNCTION

def predict_csv(file_path):

    if file_path is None:
        raise gr.Error("Please upload a CSV file.")

    # Read uploaded CSV
    data = pd.read_csv(file_path)

    if data.empty:
        raise gr.Error("The uploaded CSV is empty.")

    # Remove target column if present
    data = data.drop(columns=["Revenue"], errors="ignore")

    # Check required columns
    missing_columns = [
        col for col in X.columns if col not in data.columns
    ]

    if missing_columns:
        raise gr.Error(
            f"Missing required columns: {missing_columns}"
        )

    # Keep features in correct order
    data = data[X.columns]

    # Make predictions
    predictions = model.predict(data)
    probabilities = model.predict_proba(data)[:, 1]

    # Create results
    results = data.copy()

    results["Predicted_Revenue"] = predictions
    results["Prediction"] = [
        "Purchase" if p == 1 else "No Purchase"
        for p in predictions
    ]

    results["Purchase_Probability_%"] = (
        probabilities * 100
    ).round(2)

    # Save results
    results.to_csv(
        "/content/online_purchase_csv_results.csv",
        index=False
    )

    # Summary
    summary = (
        f"Total Customers: {len(results)}\n"
        f"Predicted Purchases: {(predictions == 1).sum()}\n"
        f"Predicted No Purchases: {(predictions == 0).sum()}"
    )

    return summary, results, "/content/online_purchase_csv_results.csv"


