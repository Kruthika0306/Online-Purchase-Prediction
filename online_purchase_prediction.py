# STEP 19: MANUAL CUSTOMER PREDICTION

def predict_manual(*values):

    # Create a customer record
    customer_data = pd.DataFrame(
        [values],
        columns=X.columns
    )

    # Predict purchase behaviour
    prediction = model.predict(customer_data)[0]

    # Calculate probabilities
    probabilities = model.predict_proba(customer_data)[0]

    no_purchase_probability = round(probabilities[0] * 100, 2)
    purchase_probability = round(probabilities[1] * 100, 2)

    result = (
        "PURCHASE" if prediction == 1
        else "NO PURCHASE"
    )

    details = pd.DataFrame({
        "Prediction": [result],
        "No Purchase Probability (%)": [no_purchase_probability],
        "Purchase Probability (%)": [purchase_probability]
    })

    return result, details


